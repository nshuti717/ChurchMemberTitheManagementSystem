    private void saveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveBtnActionPerformed
        // TODO add your handling code here:
        try {
    String username = usernameTxt.getText().trim();
    String password = new String(passwordTxt.getPassword()).trim();
    String role = (String) roleCombo.getSelectedItem();

    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Username and Password are required",
        "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    if (password.length() < 6) {
        javax.swing.JOptionPane.showMessageDialog(this, "Password must be at least 6 characters",
        "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    rw.church.model.User user = new rw.church.model.User();
    user.setUsername(username);
    user.setPassword(password);
    user.setRole(role);

    String selectedMember = (String) memberCombo.getSelectedItem();
    if (selectedMember != null && !selectedMember.isEmpty()) {
        int memberId = Integer.parseInt(selectedMember.split("\\|")[1]);
        rw.church.model.Member member = new rw.church.model.Member();
        member.setId(memberId);
        user.setMember(member);
    }

    java.rmi.registry.Registry registry = java.rmi.registry.LocateRegistry.getRegistry("127.0.0.1", 5000);
    rw.church.service.UserService service = (rw.church.service.UserService) registry.lookup("UserService");
    service.saveUser(user);
    javax.swing.JOptionPane.showMessageDialog(this, "User saved successfully", "Success",
    javax.swing.JOptionPane.INFORMATION_MESSAGE);
    loadAllUsers();
    usernameTxt.setText("");
    passwordTxt.setText("");
    memberCombo.setSelectedIndex(0);
    roleCombo.setSelectedIndex(0);
} catch (Exception ex) {
    ex.printStackTrace();
    javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error",
    javax.swing.JOptionPane.ERROR_MESSAGE);
} 
    }//GEN-LAST:event_saveBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        // TODO add your handling code here:
        int selectedRow = userTable.getSelectedRow();
if (selectedRow == -1) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please select a user to delete",
    "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
    return;
}
int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Delete this user?",
"Confirm Delete", javax.swing.JOptionPane.YES_NO_OPTION);
if (confirm != javax.swing.JOptionPane.YES_OPTION) return;
try {
    int id = (int) tableModel.getValueAt(selectedRow, 0);
    rw.church.model.User user = new rw.church.model.User();
    user.setId(id);
    java.rmi.registry.Registry registry = java.rmi.registry.LocateRegistry.getRegistry("127.0.0.1", 5000);
    rw.church.service.UserService service = (rw.church.service.UserService) registry.lookup("UserService");
    service.deleteUser(user);
    javax.swing.JOptionPane.showMessageDialog(this, "User deleted", "Success",
    javax.swing.JOptionPane.INFORMATION_MESSAGE);
    loadAllUsers();
} catch (Exception ex) {
    ex.printStackTrace();
    javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error",
    javax.swing.JOptionPane.ERROR_MESSAGE);
} 
    }//GEN-LAST:event_deleteBtnActionPerformed

