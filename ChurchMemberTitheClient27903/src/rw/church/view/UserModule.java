private void addColumnsToTable() {
    tableModel.addColumn("ID");
    tableModel.addColumn("USERNAME");
    tableModel.addColumn("ROLE");
    tableModel.addColumn("MEMBER");
    userTable.setModel(tableModel);
}

private void loadMembers() {
    try {
        java.rmi.registry.Registry registry = java.rmi.registry.LocateRegistry.getRegistry("127.0.0.1", 5000);
        rw.church.service.MemberService service = (rw.church.service.MemberService) registry.lookup("MemberService");
        java.util.List<rw.church.model.Member> list = service.findAllMembers();
        memberCombo.removeAllItems();
        for (rw.church.model.Member m : list) {
            memberCombo.addItem(m.getFullName() + "|" + m.getId());
        }
    } catch (Exception ex) { ex.printStackTrace(); }
}

private void loadAllUsers() {
    try {
        tableModel.setRowCount(0);
        java.rmi.registry.Registry registry = java.rmi.registry.LocateRegistry.getRegistry("127.0.0.1", 5000);
        rw.church.service.UserService service = (rw.church.service.UserService) registry.lookup("UserService");
        java.util.List<rw.church.model.User> list = service.findAllUsers();
        for (rw.church.model.User u : list) {
            tableModel.addRow(new Object[]{
                u.getId(), u.getUsername(), u.getRole(),
                u.getMember() != null ? u.getMember().getFullName() : "No Member"
            });
        }
    } catch (Exception ex) { ex.printStackTrace(); }
} 
